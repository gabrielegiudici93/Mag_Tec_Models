def calculate_B_field(distance_r_m, magnetic_moment_direction, mu_magnitude):
    """
    Calculates the magnetic field B generated by a magnetic dipole at a given point.

    Parameters:
    - distance_r_mm: Vector (in mm) from the dipole to the point where the field is measured.
    - magnetic_moment_direction: Unit vector indicating the direction of the magnetic moment.
    - mu_magnitude: Magnitude of the magnetic moment (e.g., in A·m²).

    Returns:
    - B_field_pT: Magnetic field vector at the point, in picoTesla (pT).
    """

    # Convert the distance vector to an array and compute its norm
    r = np.array(distance_r_m)  

    r_magnitude = np.linalg.norm(r) 
          
    # print('r_magnitude', r_magnitude)
    # Unit vector in the direction of r
    r_hat = r / r_magnitude
    # print('rhat', r_hat)
    Mu_hat = magnetic_moment_direction
    # Full magnetic moment vector (direction * magnitude)
    mu = [x * mu_magnitude for x in Mu_hat]

    # Compute the dipole field tensor: 3*r̂*r̂ᵀ - I
    tensor = 3 * np.outer(r_hat, r_hat) - np.identity(3)

    # Apply the formula: B = (μ₀ / 4π) * (tensor ⋅ μ) / |r|³
    numerator = np.matmul(tensor, mu)
    denominator = 4 * np.pi * (abs(r_magnitude)**3)

    # Magnetic field B in Tesla
    B_field = numerator / denominator

    # Convert Tesla to microTesla (1e6) or miliTesla (1e3)
    B_field_pT = B_field * 1e6   # 1000000000000000 
    # print('B_field_pT', B_field_pT)
    return B_field_pT



def generate_contact_points(MagnetPosition, z_target):
    contact_points = []

    dist_x = MagnetPosition[0,0].max() - MagnetPosition[1,0].min()  
    dist_y = MagnetPosition[0,1].max() - MagnetPosition[5,1].min()

    print('dist_x', dist_x)
    print('dist_y', dist_y)

    for magnet in MagnetPosition:
        cx, cy = magnet[0], magnet[1]
 
        points = [
            [cx, cy, z_target],                    # centro
            [cx - dist_x, cy + dist_y, z_target],  # NW
            [cx + dist_x, cy + dist_y, z_target],  # NE
            [cx - dist_x, cy - dist_y, z_target],  # SW
            [cx + dist_x, cy - dist_y, z_target],  # SE
        ]
        contact_points.extend(points)


    return contact_points, len(contact_points)  
   

def print_h5_structure(filename):
    def print_attrs(name, obj):
        if isinstance(obj, h5py.Dataset):
            print(f"[DATASET] {name}  shape={obj.shape}  dtype={obj.dtype}")
        elif isinstance(obj, h5py.Group):
            print(f"[GROUP]   {name}")

    with h5py.File(filename, "r") as f:
        print("=== ESTRUCTURA DEL ARCHIVO HDF5 ===")
        f.visititems(print_attrs)




