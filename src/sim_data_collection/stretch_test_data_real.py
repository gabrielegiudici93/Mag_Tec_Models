    def save_to_h5(self):

        filename = os.path.join("Results", "sim_experiment_force_0.0to3.0N_step0.1N_single_test50_stretch_000pct.h5")

        with h5py.File(filename, 'w') as f:

            grp = f.create_group("presses")
            
            # Lists to collect all data for top-level datasets
            all_forces = []
            all_stretchmagtec = []
            all_positions = []
            all_timestamps = []
            all_labels = []
            
            # Track cumulative index for start_idx/end_idx calculation
            cumulative_idx = 0

            for press_id in range(len(self.quadrant_real)):
                g = grp.create_group(f"press_{press_id:03d}")

                # Get data for this press
                forces_3d = np.array(self.data_Force[press_id])  # [samples, 3] (Fx, Fy, Fz)
                magtec = np.array(self.data_MagneticField[press_id])  # [samples, 15, 3]
                positions = np.array(self.data_IdenterPosition[press_id])  # [samples, 3]
                
                # Convert forces from 3D to 6D (add Tx=0, Ty=0, Tz=0)
                n_samples = forces_3d.shape[0]
                forces_6d = np.zeros((n_samples, 6), dtype=forces_3d.dtype)
                forces_6d[:, :3] = forces_3d  # Fx, Fy, Fz
                # Tx, Ty, Tz remain zeros (not available in simulation)
                
                # Generate timestamps (assuming 100 Hz sampling rate)
                timestamps = np.arange(n_samples) * 0.01
                
                # Get label (offset) for this press
                quadrant = self.quadrant_real[press_id]
                offset = quadrant if quadrant else "unknown"
                
                # Create label string matching real data format: 'pos_X_offset_press_Y_sequence_Z'
                # For simulation, we use simpler format but compatible
                label_str = f"sim_pos_{press_id:03d}_{offset}_press_0_sequence_0"
                
                # Calculate start and end indices in top-level concatenated dataset
                start_idx = cumulative_idx
                end_idx = cumulative_idx + n_samples - 1
                cumulative_idx += n_samples
                
                # Save per-press datasets
                g.create_dataset("forces", data=forces_6d)
                g.create_dataset("stretchmagtec", data=magtec)
                g.create_dataset("positions", data=positions)
                g.create_dataset("timestamps", data=timestamps)
                
                # Store attributes matching real data structure
                g.attrs["label"] = label_str.encode('utf-8') if isinstance(label_str, str) else label_str
                g.attrs["offset"] = offset.encode('utf-8') if isinstance(offset, str) else offset
                g.attrs["stretch_label"] = b"stretch_000pct"  # Can be made configurable
                g.attrs["stretch_level"] = np.float64(0.0)  # Can be made configurable
                g.attrs["start_idx"] = np.float64(start_idx)
                g.attrs["end_idx"] = np.float64(end_idx)
                
                # Calculate initial_z and max_indentation from positions
                if len(positions) > 0:
                    initial_z = np.float64(positions[0, 2])
                    max_indentation = np.float64(np.min(positions[:, 2]) - positions[0, 2])
                else:
                    initial_z = np.float64(0.0)
                    max_indentation = np.float64(0.0)
                
                g.attrs["initial_z"] = initial_z
                g.attrs["max_indentation"] = max_indentation
                
                # Collect data for top-level datasets
                all_forces.append(forces_6d)
                all_stretchmagtec.append(magtec)
                all_positions.append(positions)
                all_timestamps.append(timestamps)
                all_labels.append([label_str] * n_samples)
            
            # Create top-level concatenated datasets (matching real data structure exactly)
            # These are ALL samples from ALL presses concatenated together
            forces_concat = np.concatenate(all_forces, axis=0)
            stretchmagtec_concat = np.concatenate(all_stretchmagtec, axis=0)
            positions_concat = np.concatenate(all_positions, axis=0)
            timestamps_concat = np.concatenate(all_timestamps, axis=0)
            
            # Save in real data format (for compatibility)
            f.create_dataset("forces", data=forces_concat)
            f.create_dataset("stretchmagtec", data=stretchmagtec_concat)
            f.create_dataset("positions", data=positions_concat)
            f.create_dataset("timestamps", data=timestamps_concat)
            
            # Labels as fixed-length strings (|S64) matching real data format
            labels_flat = [item for sublist in all_labels for item in sublist]
            # Convert to fixed-length string array (64 characters max, matching real data)
            labels_array = np.array([lbl.encode('utf-8')[:64].ljust(64, b'\x00') for lbl in labels_flat], dtype='S64')
            f.create_dataset("labels", data=labels_array)
            
            # ALSO save original simulation-specific datasets (for simulation analysis)
            # forcesTest: original 3D forces (Fx, Fy, Fz only)
            forces_3d_concat = forces_concat[:, :3]  # Extract only Fx, Fy, Fz
            f.create_dataset("forcesTest", data=forces_3d_concat)
            
            # MagneticField: same as stretchmagtec (simulation naming)
            f.create_dataset("MagneticField", data=stretchmagtec_concat)
            
            # IdenterPosition: same as positions (simulation naming)
            f.create_dataset("IdenterPosition", data=positions_concat)

        print("Save data to HDF5")




    def loaddata(self, filename):
        total_samples = 0
        all_quadrants = []
        all_forces = []
        print_h5_structure(filename)


        with h5py.File(filename, 'r') as f:
            presses = f['presses']
            print(f"shape presses: {len(presses)}")

            total_samples_count = sum(f['forces'][()].shape[0] for f in presses.values())
            sample_sequence_index = np.zeros(total_samples_count, dtype=np.int32)



            current_index = 0
            for seq_id, press_key in enumerate(sorted(presses.keys())):
                press = presses[press_key]

                forces = press['forces'][:]  # [samples, 6]
                fz = forces[:, 2]  # Extract Fz component (force in Z direction)
                # timestamps = press['timestamps'][:]  
                # magnteic_field_B = press["stretchmagtec"][:]     # shape = [samples, 15, 3]

                n_samples = fz.shape[0]

                 # Asignar secuencia a cada muestra
                sample_sequence_index[current_index : current_index + n_samples] = seq_id
                current_index += n_samples
                total_samples += n_samples

                label = press.attrs.get("label", "").decode() if isinstance(press.attrs.get("label", ""), bytes) else press.attrs.get("label", "")
                quadrant = None

                if label:
                    quadrants = ["center", "ne", "nw", "se", "sw"]
                    quadrant = next((q for q in quadrants if f"_{q}_" in label), None)
                    # print(f"Quadrant: {quadrant}")
                    # print(f"Force: {fz}")
                all_quadrants.append(quadrant)
                all_forces.append(fz)

            num_presses = len(f["presses"])
            print(f"Total samples loaded: {total_samples} from {num_presses} presses.")


        return all_quadrants, all_forces, sample_sequence_index
    
